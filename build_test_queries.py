def main():
    if not CHUNKS_PATH.exists():
        raise SystemExit(f"Нет файла {CHUNKS_PATH}. Сначала выполните 'prepare'.")

    chunks = json.loads(CHUNKS_PATH.read_text(encoding="utf-8"))
    if not chunks:
        raise SystemExit("Список чанков пуст")
    errors = []
    tests = []

    for q_index, (question, answer, evidence) in enumerate(QUESTIONS, start=1):
        hits = []
        for page, needle in evidence:
            needle_norm = norm(needle)
            matches = [
                chunk for chunk in chunks
                if int(chunk.get("page", -1)) == page
                and needle_norm in norm(chunk.get("text", ""))
            ]
            if not matches:
                candidates = [
                    f"[{c['idx']}] {str(c['text'])[:95]!r}"
                    for c in chunks if int(c.get("page", -1)) == page
                ]
                errors.append(
                    f"Вопрос {q_index}: фраза {needle!r} не найдена на стр. {page}. "
                    f"Имеющиеся чанки: {candidates[:5]}"
                )
                continue

            # Если фраза есть и в перекрытии, выбираем один чанк,
            # где она лежит дальше от краёв (обычно содержит больше контекста).
            matches.sort(
                key=lambda c: min(
                    norm(c["text"]).find(needle_norm),
                    len(norm(c["text"])) - norm(c["text"]).find(needle_norm) - len(needle_norm),
                ), reverse=True,
            )
            hits.append(int(matches[0]["idx"]))

        ids = sorted(set(hits))
        if len(ids) < len(evidence):
            errors.append(f"Вопрос {q_index}: найдено только {len(ids)} из {len(evidence)} независимых чанков")
        tests.append({
            "query": question,
            "golden_chunks": ids,
            "expected_answer": answer,
        })

    if errors:
        print("Не удалось однозначно сопоставить некоторые фразы с текущим chunks.json:\n")
        for error in errors:
            print("-", error)
        raise SystemExit("Файл test_queries.py не создан. Проверьте входные чанки/фразы.")

    assert len(tests) == 15
    assert sum(len(q["golden_chunks"]) > 1 for q in tests) >= 8
    assert all(q["golden_chunks"] for q in tests)

    # Используем repr, чтобы получить корректный автономный Python-файл.
    import pprint
    header = (
        '"""Тестовая выборка по пособию «Устройство и работа поршневых ДВС» (131 с.).\n'
        'Индексы соответствуют результатам prepare на момент создания файла.\n'
        'При изменении чанкинга заново запустите build_test_queries.py.\n"""\n\n'
    )
    body = (
        "test_queries = " + pprint.pformat(tests, width=105, sort_dicts=False) + "\n\n"
        + "outliers = " + pprint.pformat(OUTLIERS, width=105, sort_dicts=False) + "\n\n"
        + "test_queries_with_outliers = test_queries + outliers\n"
    )
    OUTPUT.write_text(header + body, encoding="utf-8")
    print(f"Создано: {OUTPUT}")
    print(f"Вопросов: {len(tests)}; многоконтекстных: {sum(len(t['golden_chunks']) > 1 for t in tests)}; outliers: {len(OUTLIERS)}")
    for i, test in enumerate(tests, 1):
        print(f"{i:2d}. {test['golden_chunks']}: {test['query']}")


if __name__ == "__main__":
    main()
